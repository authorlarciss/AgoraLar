"""Интерфейс анализатора: байты → производный артефакт (ADR-0018).

Анализатор живёт **вне ядра**: ядро только хранит байты и провенанс.
Плагин-анализатор не импортирует продукт — он отдаёт обычные данные,
поэтому интерфейс здесь структурный (`Protocol`), а не базовый класс:
подходит любой объект с тремя методами.

Версия анализатора нужна провенансу: при смене алгоритма старое значение
должно быть отличимо от нового (ADR-0018 ядра про `derived_by`).
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class IAnalyzer(Protocol):
    """Что обязан уметь плагин вида `analyzer`."""

    @property
    def version(self) -> str:
        """Версия алгоритма — попадает в `Provenance.version`."""

    def describe(self) -> str:
        """Человекочитаемое описание: чем анализирует и что производит."""

    def accepts(self, media_type: str) -> bool:
        """Годится ли входной артефакт этому анализатору."""

    def analyze(self, data: bytes, media_type: str) -> tuple[str, bytes, str]:
        """Производные данные: `(роль, байты, media_type)`.

        Роль — имя, под которым результат прикрепится к объекту
        (`preview`, `embedding`, ...). Возвращать `Artifact` нельзя: плагин
        не должен зависеть от ядра, а продукт сам посчитает адрес.
        """


__all__ = ["IAnalyzer"]
